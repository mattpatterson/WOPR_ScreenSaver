# Converts Natural Earth 110m (public domain) data into compact base64 blobs embedded in Swift.
# Blob format: little-endian Int16 stream: [count, lon0*100, lat0*100, ...] per polyline.
#   coast: coastlines + major lakes (drawn teal)
#   usa:   outline of the United States (drawn blue)
#   ussr:  outer outline of the 15 Soviet republics, internal borders dissolved (drawn red)
import json, struct, base64, sys
coast, lakes, countries, out = sys.argv[1:5]
USSR = {'RUS','UKR','BLR','KAZ','UZB','TKM','KGZ','TJK','GEO','ARM','AZE','MDA','LTU','LVA','EST'}

def rings(geom):
    polys = [geom['coordinates']] if geom['type'] == 'Polygon' else geom['coordinates']
    for p in polys:
        yield p[0]

def q(pt): return (round(pt[0] * 100), round(pt[1] * 100))

def dissolve(ring_list):
    # Edge cancellation: shared borders appear in two rings and cancel out.
    count = {}
    edges = []
    for r in ring_list:
        pts = [q(p) for p in r]
        for a, b in zip(pts, pts[1:]):
            if a == b: continue
            k = (min(a, b), max(a, b))
            count[k] = count.get(k, 0) + 1
            edges.append((a, b))
    keep = [(a, b) for a, b in edges if count[(min(a, b), max(a, b))] == 1]
    # Chain into polylines.
    nxt = {}
    for a, b in keep: nxt.setdefault(a, []).append(b)
    lines = []
    used = set()
    for a, b in keep:
        if (a, b) in used: continue
        line = [a, b]; used.add((a, b))
        cur = b
        while True:
            cand = [c for c in nxt.get(cur, []) if (cur, c) not in used]
            if not cand: break
            c = cand[0]; used.add((cur, c)); line.append(c); cur = c
            if cur == line[0]: break
        lines.append([(x / 100, y / 100) for x, y in line])
    return lines

def blob(lines):
    buf = bytearray()
    for ln in lines:
        buf += struct.pack('<h', len(ln))
        for lon, lat in ln:
            buf += struct.pack('<hh', round(lon * 100), round(lat * 100))
    return base64.b64encode(bytes(buf)).decode(), len(buf)

coast_lines = [f['geometry']['coordinates'] for f in json.load(open(coast))['features']]
for f in json.load(open(lakes))['features']:
    if f['properties'].get('scalerank', 9) > 0: continue
    coast_lines += list(rings(f['geometry']))
feats = json.load(open(countries))['features']
usa = [r for f in feats if f['properties']['ADM0_A3'] == 'USA' for r in rings(f['geometry'])]
ussr = dissolve([r for f in feats if f['properties']['ADM0_A3'] in USSR for r in rings(f['geometry'])])

def emit(fh, name, lines):
    b, n = blob(lines)
    chunks = [b[i:i+120] for i in range(0, len(b), 120)]
    fh.write('    static let %s: String = """\n%s\n"""\n' % (name, '\n'.join(chunks)))
    print(name, 'polylines', len(lines), 'bytes', n)

with open(out, 'w') as fh:
    fh.write('// Generated by tools/gen_map.py from Natural Earth 110m data (public domain).\n// Do not edit by hand.\n\nenum MapData {\n')
    emit(fh, 'base64', coast_lines)
    emit(fh, 'usa', usa)
    emit(fh, 'ussr', ussr)
    fh.write('}\n')
